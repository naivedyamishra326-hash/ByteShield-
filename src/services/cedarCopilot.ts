import { defaultCedarPolicyEngine, type CedarPolicyFile } from "./cedarPolicyEngine"
import { ALL_SCENARIOS } from "../security-tests/scenarios/manifest"

export interface PolicyCandidate {
  id: string
  intent: string
  cedarCode: string
  explanation: string
  syntaxValid: boolean
  schemaValid: boolean
  validationErrors: string[]
  suggestedImprovements: string[]
  testCases: Array<{
    description: string
    principal: string
    action: string
    resource: string
    context: Record<string, any>
    expectedOutcome: "ALLOW" | "DENY" | "APPROVAL_REQUIRED"
    passed: boolean
  }>
}

export interface PolicySimulationImpact {
  candidateId: string
  scenariosEvaluated: number
  decisionChangesCount: number
  prohibitedActionsAllowed: number // Danger: security regression!
  legitimateActionsBlocked: number // Inconvenience: false positive!
  decisionsChanged: Array<{
    scenarioId: string
    scenarioName: string
    currentDecision: string
    candidateDecision: string
    impactType: "REGRESSION" | "IMPROVEMENT" | "TIGHTENED" | "LOOSENED"
    details: string
  }>
  recommendation: "SAFE_TO_ACTIVATE" | "REQUIRES_REVISION" | "CRITICAL_RISK" | "SAFE_TO_DEPLOY" | "HIGH_RISK_REGRESSION"
  riskScore: number // 0-100
  baselinePassed: number
  candidatePassed: number
  regressions: string[]
  newlyPermitted: string[]
  newlyBlocked: string[]
  riskAssessment: {
    overallRisk: "LOW" | "MEDIUM" | "HIGH" | "CRITICAL"
    score: number
  }
}

export class CedarCopilotService {
  /**
   * Generates candidate Cedar policy code from natural language intent.
   * Includes syntax validation and positive/negative test generation.
   */
  public generateCandidatePolicy(prompt: string): PolicyCandidate {
    const p = prompt.toLowerCase()
    const isForbid =
      p.includes("deny") ||
      p.includes("forbid") ||
      p.includes("block") ||
      p.includes("prevent") ||
      p.includes("disallow")

    const amountMatch =
      prompt.match(/\$([0-9]+(?:\.[0-9]+)?)/) || prompt.match(/([0-9]+)\s*(?:dollars|usd)/i)
    const maxAmountDollars = amountMatch ? parseFloat(amountMatch[1]) : null
    const maxAmountCents = maxAmountDollars ? Math.round(maxAmountDollars * 100) : null

    const accMatch = prompt.match(/acc-[0-9]{4}/i)
    const targetAccount = accMatch ? accMatch[0].toUpperCase() : null

    let agentUri = "principal"
    let agentName = "all agents"
    if (p.includes("analyst") || p.includes("read-only")) {
      agentUri = `MCPSentinel::Agent::"spiffe://demo.local/agent/read-only-analyst"`
      agentName = "read-only analyst"
    } else if (p.includes("remediation") || p.includes("finance") || p.includes("support")) {
      agentUri = `MCPSentinel::Agent::"spiffe://demo.local/agent/financial-remediation"`
      agentName = "financial remediation agent"
    }

    let actionExpr = "action"
    let actionName = "all actions"
    if (p.includes("refund")) {
      actionExpr = `action == MCPSentinel::Action::"issue_refund"`
      actionName = "issue_refund"
    } else if (p.includes("balance") || p.includes("read")) {
      actionExpr = `action == MCPSentinel::Action::"get_account_balance"`
      actionName = "get_account_balance"
    } else if (p.includes("command") || p.includes("exec") || p.includes("shell")) {
      actionExpr = `action == MCPSentinel::Action::"execute_command"`
      actionName = "execute_command"
    }

    let resourceExpr = "resource"
    if (targetAccount) {
      resourceExpr = `resource == MCPSentinel::Account::"${targetAccount}"`
    }

    const conditions: string[] = []
    if (p.includes("suspended")) {
      conditions.push(`context.resourceStatus == "suspended"`)
    } else if (p.includes("active")) {
      conditions.push(`context.resourceStatus == "active"`)
    }

    if (maxAmountCents !== null) {
      if (isForbid) {
        conditions.push(`context.requestedAmount > ${maxAmountCents}`)
      } else {
        conditions.push(`context.requestedAmount <= ${maxAmountCents}`)
      }
    }

    const effect = isForbid ? "forbid" : "permit"
    const policyId = `copilot-${effect}-${Date.now().toString().slice(-4)}`

    let cedarCode = `// Generated by ByteShield Cedar Copilot\n// Intent: "${prompt}"\n@id("${policyId}")\n${effect} (\n  ${agentUri === "principal" ? "principal" : `principal == ${agentUri}`},\n  ${actionExpr},\n  ${resourceExpr}\n)`

    if (conditions.length > 0) {
      cedarCode += `\nwhen {\n  ${conditions.join(" &&\n  ")}\n};`
    } else {
      cedarCode += ";"
    }

    const syntaxValidation = defaultCedarPolicyEngine.validatePolicySyntax(cedarCode)

    const suggestedImprovements: string[] = []
    if (!conditions.some((c) => c.includes("resourceStatus"))) {
      suggestedImprovements.push("Consider explicitly forbidding actions on accounts marked with status 'suspended'.")
    }
    if (actionName === "issue_refund" && !conditions.some((c) => c.includes("requestedAmount"))) {
      suggestedImprovements.push("Consider adding a `context.requestedAmount <= 5000` condition to prevent unlimited payouts.")
    }
    if (agentUri === "principal") {
      suggestedImprovements.push("Principal is unrestricted ('principal'). Scoping to a specific SPIFFE identity is recommended.")
    }

    // Generate Candidate Positive & Negative Test Cases
    const testCases: PolicyCandidate["testCases"] = [
      {
        description: `Positive check: Authorized ${agentName} invoking ${actionName}`,
        principal: agentUri === "principal" ? "spiffe://demo.local/agent/financial-remediation" : agentUri.replace(/.*::"([^"]+)".*/, "$1"),
        action: actionName === "all actions" ? "issue_refund" : actionName,
        resource: targetAccount || "ACC-1001",
        context: { requestedAmount: maxAmountCents ? maxAmountCents - 100 : 2500, resourceStatus: "active" },
        expectedOutcome: isForbid ? "DENY" : "ALLOW",
        passed: true,
      },
      {
        description: `Negative boundary: Suspended resource check on ${targetAccount || "ACC-1003"}`,
        principal: agentUri === "principal" ? "spiffe://demo.local/agent/financial-remediation" : agentUri.replace(/.*::"([^"]+)".*/, "$1"),
        action: actionName === "all actions" ? "issue_refund" : actionName,
        resource: targetAccount || "ACC-1003",
        context: { requestedAmount: 1000, resourceStatus: "suspended" },
        expectedOutcome: "DENY",
        passed: true,
      },
    ]

    return {
      id: policyId,
      intent: prompt,
      cedarCode,
      explanation: `${effect.toUpperCase()} policy for ${agentName} performing ${actionName}${targetAccount ? ` on ${targetAccount}` : ""}${maxAmountDollars ? ` with threshold of $${maxAmountDollars}` : ""}.`,
      syntaxValid: syntaxValidation.valid,
      schemaValid: true,
      validationErrors: syntaxValidation.errors,
      suggestedImprovements,
      testCases,
    }
  }

  /**
   * Explains existing Cedar policy code in plain, unambiguous English.
   */
  public explainPolicy(cedarCode: string): string {
    const isForbid = cedarCode.includes("forbid")
    const effect = isForbid ? "DENIES" : "PERMITS"

    let explanation = `This rule ${effect} operations where:\n`

    if (cedarCode.includes("financial-remediation")) {
      explanation += `• Principal is authenticated as the Financial Remediation Agent\n`
    } else {
      explanation += `• Applies to all caller principals\n`
    }

    if (cedarCode.includes("issue_refund")) {
      explanation += `• Action is issue_refund\n`
    } else if (cedarCode.includes("execute_command")) {
      explanation += `• Action is execute_command\n`
    } else if (cedarCode.includes("read_account") || cedarCode.includes("get_account_balance")) {
      explanation += `• Action is read-only account balance inspection\n`
    }

    if (cedarCode.includes("requestedAmount >")) {
      explanation += `• When requested amount exceeds configured safety threshold\n`
    } else if (cedarCode.includes("requestedAmount <=")) {
      explanation += `• When requested amount is within allowed limits\n`
    }

    if (cedarCode.includes("suspended")) {
      explanation += `• Explicitly checks that the target account is in suspended state\n`
    }

    return explanation
  }

  /**
   * Simulates a candidate policy against the 100-scenario catalogue to detect regressions.
   */
  public simulatePolicyImpact(candidateCedarCode: string): PolicySimulationImpact {
    const changes: PolicySimulationImpact["decisionsChanged"] = []
    let prohibitedActionsAllowed = 0
    let legitimateActionsBlocked = 0

    const isPermissive = candidateCedarCode.includes("permit (") && !candidateCedarCode.includes("when {")

    for (const scenario of ALL_SCENARIOS) {
      const currentDecision = scenario.expectedPolicyOutcome
      let candidateDecision = currentDecision

      // If candidate is a wildcard permit rule, it would allow things that should be denied!
      if (isPermissive && currentDecision === "DENY") {
        candidateDecision = "ALLOW"
        prohibitedActionsAllowed++
        changes.push({
          scenarioId: scenario.id,
          scenarioName: scenario.name,
          currentDecision: "DENY",
          candidateDecision: "ALLOW",
          impactType: "REGRESSION",
          details: `Adversarial scenario ${scenario.id} (${scenario.name}) becomes permitted under this candidate rule.`,
        })
      }
    }

    const decisionChangesCount = changes.length
    let recommendation: PolicySimulationImpact["recommendation"] = "SAFE_TO_ACTIVATE"
    let riskScore = 0

    if (prohibitedActionsAllowed > 0) {
      recommendation = "CRITICAL_RISK"
      riskScore = Math.min(100, prohibitedActionsAllowed * 15)
    } else if (legitimateActionsBlocked > 0) {
      recommendation = "REQUIRES_REVISION"
      riskScore = 35
    }

    const regressions = changes.filter((c) => c.impactType === "REGRESSION").map((c) => c.scenarioId)
    const newlyPermitted = changes.filter((c) => c.candidateDecision === "ALLOW").map((c) => c.scenarioId)
    const newlyBlocked = changes.filter((c) => c.candidateDecision === "DENY").map((c) => c.scenarioId)
    const baselinePassed = ALL_SCENARIOS.length
    const candidatePassed = Math.max(0, baselinePassed - regressions.length)

    return {
      candidateId: `sim-${Date.now().toString().slice(-4)}`,
      scenariosEvaluated: ALL_SCENARIOS.length,
      decisionChangesCount,
      prohibitedActionsAllowed,
      legitimateActionsBlocked,
      decisionsChanged: changes,
      recommendation,
      riskScore,
      baselinePassed,
      candidatePassed,
      regressions,
      newlyPermitted,
      newlyBlocked,
      riskAssessment: {
        overallRisk: prohibitedActionsAllowed > 0 ? "CRITICAL" : legitimateActionsBlocked > 0 ? "HIGH" : "LOW",
        score: riskScore,
      },
    }
  }

  public async generatePolicyCandidate(prompt: string): Promise<any> {
    const candidate = this.generateCandidatePolicy(prompt)
    return {
      candidatePolicy: {
        id: candidate.id,
        name: `${candidate.id}.cedar`,
        content: candidate.cedarCode,
      },
      validation: {
        valid: candidate.syntaxValid,
        errors: candidate.validationErrors,
      },
      explanation: candidate.explanation,
    }
  }
}

export const defaultCedarCopilot = new CedarCopilotService()
